"""Session 52: convert the generated manuscript (lab/paper/manuscript.md) into a XeLaTeX/LuaLaTeX source for Overleaf.

No TeX or pandoc exists on this machine (paper/STATUS, open point 6), so the output is UNTESTED: it has never been compiled.
It is a mechanical conversion of the markdown subset build_manuscript.py writes (headings, paragraphs, **bold**, *italic*,
`code`, bullet/numbered lists, pipe tables, figure captions, bare URLs, a few wikilinks); text is copied verbatim, Unicode
symbols are kept and need a Unicode engine (XeLaTeX or LuaLaTeX) with a font that covers Greek, sub/superscript digits and
arrows (DejaVu Serif is set; change it in the preamble). Figures: the four main-text figures are mapped to their PNG files by
the plan in draft_short.md and copied into lab/paper/tex/figures/.
  python lab/paper/build_manuscript.py && python lab/paper/build_tex.py      # -> lab/paper/tex/manuscript.tex
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "tex"
MAIN_FIGS = ("fig_main1_steering", "fig10_r5_speed", "fig8_r6_r8_switch_cost", "fig13_minibatch_confirmed")

PREAMBLE = r"""% Generated by lab/paper/build_tex.py from manuscript.md -- do not edit by hand. UNTESTED (never compiled).
% Compile with XeLaTeX or LuaLaTeX (Overleaf: Menu -> Compiler).
\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{fontspec}
\setmainfont{DejaVu Serif}
\setmonofont{DejaVu Sans Mono}[Scale=0.85]
\usepackage{graphicx}
\usepackage{tabularx}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{xurl}
\setlist{nosep}
"""

SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}",
           "\U0001D7D9": r"\textbf{1}"}


def esc(s: str) -> str:
    return "".join(SPECIAL.get(c, c) for c in s)


def inline(s: str) -> str:
    """Escape and convert inline markdown; code spans and URLs are protected first."""
    s = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", s)
    s = re.sub(r"\[\[([^\]]+)\]\]", r"\1", s)
    protected: list[str] = []

    def keep(m: re.Match) -> str:
        if m.group(1) is not None:
            protected.append(r"\texttt{" + esc(m.group(1)) + "}")
        else:
            protected.append(r"\url{" + m.group(2).replace("%", r"\%").replace("#", r"\#") + "}")
        return f"\x00{len(protected) - 1}\x00"

    t = esc(re.sub(r"`([^`]+)`|(https?://[^\s)\]]+[^\s)\].,;])", keep, s).replace("\x00", "\x01"))
    t = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", t)
    t = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\\emph{\1}", t)
    return re.sub("\x01(\\d+)\x01", lambda m: protected[int(m.group(1))], t)


def table(rows: list[str]) -> list[str]:
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
    cells = [c for c in cells if not all(re.fullmatch(r":?-{2,}:?", x) for x in c)]
    n = max(len(c) for c in cells)
    out = [r"\begin{center}\footnotesize", r"\begin{tabularx}{\linewidth}{" + "X" * n + "}", r"\hline"]
    for i, c in enumerate(cells):
        out.append(" & ".join(inline(x) for x in c + [""] * (n - len(c))) + r" \\" + (r" \hline" if i == 0 else ""))
    return out + [r"\hline", r"\end{tabularx}", r"\end{center}"]


def convert(md: str) -> str:
    lines = md.split("\n")
    if lines and lines[0] == "---":                      # drop Obsidian front matter
        lines = lines[lines.index("---", 1) + 1:]
    body, i, in_abs, fig_no = [], 0, False, 0
    stack: list[tuple[int, str]] = []                    # open lists: (indent, environment)
    title = next(l[2:] for l in lines if l.startswith("# "))

    def close_list(indent: int = -1) -> None:
        while stack and stack[-1][0] > indent:
            body.append(r"\end{" + stack.pop()[1] + "}")

    while i < len(lines):
        l = lines[i].rstrip()
        if l.startswith("|"):
            close_list()
            j = i
            while j < len(lines) and lines[j].startswith("|"):
                j += 1
            body += table(lines[i:j])
            i = j
            continue
        m_item = re.match(r"^(\s*)(- |\d+\. )(.*)$", l)
        if m_item:
            indent, kind = len(m_item.group(1)), "itemize" if m_item.group(2) == "- " else "enumerate"
            close_list(indent)
            if stack and stack[-1][0] == indent and stack[-1][1] != kind:
                body.append(r"\end{" + stack.pop()[1] + "}")
            if not stack or stack[-1][0] < indent:
                body.append(r"\begin{" + kind + "}")
                stack.append((indent, kind))
            body.append(r"\item " + inline(m_item.group(3)))
            i += 1
            continue
        if stack and l.startswith(" ") and l.strip():   # continuation line of the current item
            body[-1] += " " + inline(l.strip())
            i += 1
            continue
        close_list()
        if l.startswith("# ") and l[2:] == title:
            pass
        elif l.startswith("# "):
            body += [r"\clearpage", r"\appendix", r"\section*{" + inline(l[2:]) + "}"]
        elif l.startswith("## "):
            h = l[3:]
            if in_abs:
                body.append(r"\end{abstract}")
                in_abs = False
            if h == "Abstract":
                body.append(r"\begin{abstract}")
                in_abs = True
            elif h == "Figures":
                pass
            else:
                body.append(r"\section*{" + inline(h) + "}")
        elif l.startswith("#### ") or l.startswith("### "):
            body.append(r"\subsection*{" + inline(l.split(" ", 1)[1]) + "}")
        elif re.match(r"^\*Figure (\d+)\.\* ", l) and fig_no < len(MAIN_FIGS) and "## Figures" in "\n".join(lines[:i]):
            cap = re.sub(r"^\*Figure \d+\.\* ", "", l)
            body += [r"\begin{figure}[t]", r"\centering",
                     r"\includegraphics[width=\linewidth]{figures/" + MAIN_FIGS[fig_no] + ".png}",
                     r"\caption{" + inline(cap) + "}", r"\end{figure}"]
            fig_no += 1
        elif l.strip():
            body.append(inline(l))
        else:
            body.append("")
        i += 1
    close_list()
    if in_abs:
        body.append(r"\end{abstract}")
    head = PREAMBLE + r"\title{" + inline(title) + "}\n" + r"\author{Authors to be decided}" + "\n" + r"\date{}" + "\n"
    return head + "\\begin{document}\n\\maketitle\n" + "\n".join(body) + "\n\\end{document}\n"


def main() -> None:
    md = (HERE / "manuscript.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    for f in MAIN_FIGS:
        shutil.copyfile(HERE / "figures" / f"{f}.png", OUT / "figures" / f"{f}.png")
    tex = convert(md)
    (OUT / "manuscript.tex").write_text(tex, encoding="utf-8")
    opens = len(re.findall(r"(?<!\\)\{", tex)) - len(re.findall(r"(?<!\\)\}", tex))
    envs = {e: (tex.count(r"\begin{" + e + "}"), tex.count(r"\end{" + e + "}"))
            for e in ("itemize", "enumerate", "figure", "tabularx", "abstract")}
    print(f"lines {tex.count(chr(10))}; brace balance {opens}; environments {envs}; figures {tex.count('includegraphics')}")


if __name__ == "__main__":
    main()
